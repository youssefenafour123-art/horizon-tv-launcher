"""Builds the Riwaq app icon and TV banner as Android vector drawables (lettering turned into outlines)."""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, 'web', 'fonts')
RES = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res', 'drawable')

def text_path(font_file, chars, x, baseline, size, tracking=0.0):
    f = TTFont(os.path.join(FONTS, font_file))
    gs, cmap, upm = f.getGlyphSet(), f.getBestCmap(), f['head'].unitsPerEm
    hmtx = f['hmtx']
    s = size / upm
    pen = SVGPathPen(gs)
    for ch in chars:
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        x += hmtx[g][0] * s + tracking * size
    return pen.getCommands(), x

MARK = '''
    <path android:strokeColor="#FFC9A15B" android:strokeWidth="{sw}" android:pathData="{arch}" />
    <path android:fillColor="#FFE0B46A" android:pathData="{sun}" />
    <path android:strokeColor="#FFC9A15B" android:strokeWidth="{lw}" android:strokeLineCap="round" android:pathData="{lines}" />'''

def mark(ox, oy, k, sw=6, lw=3):
    """the mark drawn from its 120x120 design, scaled by k and moved to (ox, oy)"""
    X = lambda v: f'{ox + v * k:.2f}'
    Y = lambda v: f'{oy + v * k:.2f}'
    r = 36 * k
    arch = f'M{X(30)},{Y(112)} L{X(30)},{Y(70)} A{r:.2f},{r:.2f} 0 1,1 {X(90)},{Y(70)} L{X(90)},{Y(112)}'
    sr = 10 * k
    sun = f'M{X(50)},{Y(74)} a{sr:.2f},{sr:.2f} 0 1,0 {2*sr:.2f},0 a{sr:.2f},{sr:.2f} 0 1,0 {-2*sr:.2f},0z'
    lines = f'M{X(42)},{Y(92)}H{X(78)}M{X(48)},{Y(100)}H{X(72)}M{X(54)},{Y(108)}H{X(66)}'
    return MARK.format(arch=arch, sun=sun, lines=lines, sw=f'{sw*k:.2f}', lw=f'{lw*k:.2f}')

STAR = 'M20 2l5 9 9-5-5 9 9 5-9 5 5 9-9-5-5 9-5-9-9 5 5-9-9-5 9-5-5-9 9 5z'

def gradient_rect(w, h):
    return f'''
    <path android:pathData="M0,0h{w}v{h}h-{w}z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{w*0.18:.0f}" android:centerY="{h*0.3:.0f}" android:gradientRadius="{w*0.95:.0f}">
                <item android:offset="0" android:color="#FF1A4144" />
                <item android:offset="0.55" android:color="#FF0F2A2C" />
                <item android:offset="1" android:color="#FF0A1A1B" />
            </gradient>
        </aapt:attr>
    </path>'''

def banner():
    lat, _ = text_path('marcellus.woff2', 'RIWAQ', 128, 90, 38, 0.1)
    # رواق: none of its letters join the next one, so the isolated forms laid out right-to-left are exact
    ar, _ = text_path('amiri-ar-bold.woff2', 'قاور', 131, 128, 32)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/make_drawables.py: 320x180 Android TV banner -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="320dp" android:height="180dp" android:viewportWidth="320" android:viewportHeight="180">{gradient_rect(320, 180)}
    <group android:translateX="296" android:translateY="14" android:scaleX="0.3" android:scaleY="0.3">
        <path android:fillColor="#8CC9A15B" android:pathData="{STAR}" />
    </group>{mark(26, 40, 0.8)}
    <path android:fillColor="#FFF1E7D6" android:pathData="{lat}" />
    <path android:fillColor="#FFC9A15B" android:pathData="{ar}" />
</vector>
'''

def icon():
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/make_drawables.py: app icon -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M24,0h60a24,24 0 0 1 24,24v60a24,24 0 0 1 -24,24h-60a24,24 0 0 1 -24,-24v-60a24,24 0 0 1 24,-24z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="32" android:centerY="22" android:gradientRadius="120">
                <item android:offset="0" android:color="#FF1A4144" />
                <item android:offset="0.7" android:color="#FF0F2A2C" />
                <item android:offset="1" android:color="#FF0A1A1B" />
            </gradient>
        </aapt:attr>
    </path>{mark(15, 13, 0.65, sw=7, lw=4)}
</vector>
'''

os.makedirs(RES, exist_ok=True)
open(os.path.join(RES, 'banner.xml'), 'w', encoding='utf-8').write(banner())
open(os.path.join(RES, 'ic_launcher.xml'), 'w', encoding='utf-8').write(icon())
# the same artwork as SVG for the brand sheet and README
def to_svg(xml, w, h):
    import re
    body = ''
    for m in re.finditer(r'<path ([^>]*?)(/>|>)', xml):
        a = dict(re.findall(r'android:(\w+)="([^"]*)"', m.group(1)))
        fill = a.get('fillColor', 'none'); stroke = a.get('strokeColor')
        conv = lambda c: '#' + c[3:] if c and len(c) == 9 else c
        attrs = f'd="{a["pathData"]}" fill="{conv(fill) if fill != "none" else "url(#g)"}"'
        if fill == 'none' and stroke: attrs = f'd="{a["pathData"]}" fill="none"'
        if stroke: attrs += f' stroke="{conv(stroke)}" stroke-width="{a["strokeWidth"]}"' + (' stroke-linecap="round"' if a.get('strokeLineCap') else '')
        if a.get('fillColor', '').startswith('#8C'): attrs += ' transform="translate(296 14) scale(.3)" fill-opacity=".55"'
        body += f'<path {attrs}/>'
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}"><defs><radialGradient id="g" cx=".18" cy=".3" r=".95"><stop offset="0" stop-color="#1A4144"/><stop offset=".55" stop-color="#0F2A2C"/><stop offset="1" stop-color="#0A1A1B"/></radialGradient></defs>{body}</svg>'
open(os.path.join(ROOT, 'brand', 'banner.svg'), 'w', encoding='utf-8').write(to_svg(banner(), 320, 180))
